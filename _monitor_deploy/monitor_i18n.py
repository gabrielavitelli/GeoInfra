def ui_lang() -> str:
    if st is not None and hasattr(st, "session_state"):
        return st.session_state.get("ui_lang", "pt")
    return "pt"


def t(key: str) -> str:
    lang = ui_lang()
    return STRINGS.get(lang, STRINGS["pt"]).get(key, STRINGS["pt"].get(key, key))


def nav_items_for_lang():
    """Lista (emoji, label_exibido, page_key_pt) para o dispatcher."""
    d = STRINGS.get(ui_lang(), STRINGS["pt"])
    return [(ic, d.get(k_nav, k_nav), page_key) for ic, k_nav, page_key in NAV_DEF]
